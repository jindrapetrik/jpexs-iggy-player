import com.jpexs.decompiler.flash.abc.avm2.AVM2Code;
import com.jpexs.decompiler.flash.abc.avm2.instructions.InstructionDefinition;
import com.jpexs.decompiler.flash.abc.avm2.instructions.AVM2Instruction;
import com.jpexs.decompiler.flash.SWF;
import com.jpexs.decompiler.flash.abc.ABC;
import com.jpexs.decompiler.flash.tags.DoABC2Tag;
import java.io.*;
import java.nio.file.*;

public class GenerateRuntimeOpcodes {
    public static void main(String[] args) throws Exception {
        StringBuilder output = new StringBuilder("// Generated by tools/GenerateRuntimeOpcodes.java from FFDec's AVM2 operand table.\nnamespace IggyViewer {\n    internal sealed partial class RuntimeAbc {\n        static readonly string[] opcodeFormats = (\n");
        for (int row = 0; row < 16; row++) {
            output.append("            \"");
            for (int i = row * 16; i < row * 16 + 16; i++) {
                InstructionDefinition definition = AVM2Code.instructionSet[i];
                if (definition == null) output.append('?');
                else for (int operand : definition.operands) {
                    switch (operand & 0xff00) {
                        case AVM2Code.OPT_U30: case AVM2Code.OPT_S16: output.append(operand == AVM2Code.DAT_MULTINAME_INDEX ? 'n' : 'u'); break;
                        case AVM2Code.OPT_U8: case AVM2Code.OPT_S8: output.append('b'); break;
                        case AVM2Code.OPT_S24: output.append('j'); break;
                        case AVM2Code.OPT_CASE_OFFSETS: output.append('s'); break;
                        default: throw new IllegalStateException("Unknown operand encoding");
                    }
                }
                if (i != 255) output.append('|');
            }
            output.append(row == 15 ? "\").Split('|');\n" : "\" +\n");
        }
        output.append("    }\n}\n");
        Files.writeString(Paths.get(args[0]), output);
        SWF swf = new SWF(new FileInputStream(args[1]), false); ABC abc = null;
        for (com.jpexs.decompiler.flash.tags.Tag tag : swf.getTags()) if (tag instanceof DoABC2Tag) { abc = ((DoABC2Tag) tag).getABC(); break; }
        int qname = 1;
        while (abc.constants.getMultiname(qname).kind != 7) qname++;
        StringBuilder effects = new StringBuilder("// Generated by tools/GenerateRuntimeOpcodes.java.\nnamespace IggyViewer {\n    internal sealed partial class RuntimeAbc {\n        static readonly int[][] stackEffects = new int[][] {\n");
        for (int i = 0; i < 256; i++) {
            InstructionDefinition d = AVM2Code.instructionSet[i]; int pop = -1, push = 0, argument = -1, coefficient = 0;
            if (d != null) try {
                int[] operands = new int[d.operands.length];
                for (int n = 0; n < operands.length; n++) if (d.operands[n] == AVM2Code.DAT_MULTINAME_INDEX) operands[n] = qname;
                AVM2Instruction instruction = new AVM2Instruction(0, d, operands);
                pop = d.getStackPopCount(instruction, abc); push = d.getStackPushCount(instruction, abc);
                for (int n = 0; n < operands.length; n++) if (d.operands[n] != AVM2Code.DAT_MULTINAME_INDEX) {
                    operands[n] = 1; int delta = d.getStackPopCount(instruction, abc) - pop; operands[n] = 0;
                    if (delta != 0) { argument = n; coefficient = delta; }
                }
            } catch (Exception ignored) { pop = -1; }
            effects.append("            new int[]{").append(pop).append(',').append(push).append(',').append(argument).append(',').append(coefficient).append("}, // ").append(Integer.toHexString(i)).append('\n');
        }
        effects.append("        };\n    }\n}\n"); Files.writeString(Paths.get(args[2]), effects);
    }
}
